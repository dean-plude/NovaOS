# Microsoft.UI.Input.dll's build hooks (tools/build_userland.py calls them
# with itself as b).  The DLL is C++ (no exceptions, no RTTI, no C++
# library) against the Windows Runtime ABI headers tools/winrt/abigen.py
# generates, as winrtabitest is.  Each lifted interface it implements gets
# a default implementation generated here (stubs.h, Stub<I>): a getter
# hands back zeros, a setter and an event's add and remove succeed, any
# other method says E_NOTIMPL and names itself on the debug output; the
# classes in the .cpp files derive from Stub<I> and override what they do.
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

# the ABI headers whose interfaces get stubs
HEADERS = ('microsoft.ui.h', 'microsoft.ui.content.h', 'microsoft.ui.input.h', 'microsoft.ui.windowing.h')

IFACE = re.compile(r'struct __declspec\(uuid\("[^"]+"\)\) __declspec\(novtable\) (\w+) : public \w+\s*\{(.*?)\n\};', re.S)
METHOD = re.compile(r'virtual HRESULT STDMETHODCALLTYPE (\w+)\((.*)\) = 0;')
NAMESPACE = {'microsoft.ui.h': 'ABI::Microsoft::UI', 'microsoft.ui.content.h': 'ABI::Microsoft::UI::Content',
             'microsoft.ui.input.h': 'ABI::Microsoft::UI::Input', 'microsoft.ui.windowing.h': 'ABI::Microsoft::UI::Windowing'}


def split_params(text):
    """a parameter list's parameters (commas inside <> do not split)"""
    out, depth, cur = [], 0, ''
    for c in text:
        if c == '<':
            depth += 1
        elif c == '>':
            depth -= 1
        if c == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def stubs(abi):
    """stubs.h's text from the ABI headers in directory @abi"""
    lines = ['/* Generated by userland/microsoft_ui_input/build.py from the Windows Runtime ABI headers: do not edit. */',
             '#pragma once', 'template <class I> struct Stub;']
    for h in HEADERS:
        lines.append(f'#include <{h}>')
    for h in HEADERS:
        text = open(os.path.join(abi, h)).read()
        ns = NAMESPACE[h]
        for m in IFACE.finditer(text):
            name, body = m.group(1), m.group(2)
            lines.append(f'template <> struct Stub<{ns}::{name}> : {ns}::{name}\n{{')
            for mm in METHOD.finditer(body):
                meth, params = mm.group(1), split_params(mm.group(2))
                names = [p.split()[-1].lstrip('*&') for p in params]
                ptrs = [n for p, n in zip(params, names) if p[:p.rfind(n)].strip().endswith('*')]
                getter = meth.startswith('get_')
                body_lines = []
                if getter:
                    body_lines += [f'if ({n}) memset((void *){n}, 0, sizeof *{n});' for n in ptrs]
                    ret = 'S_OK'
                elif meth.startswith(('put_', 'add_', 'remove_')):
                    body_lines += [f'if ({n}) memset((void *){n}, 0, sizeof *{n});' for p, n in zip(params, names)
                                   if n in ptrs and 'EventRegistrationToken' in p]
                    ret = 'S_OK'
                else:
                    body_lines += [f'if ({n}) memset((void *){n}, 0, sizeof *{n});' for p, n in zip(params, names)
                                   if n in ptrs and (p.count('*') >= 2 or 'resultLength' in n or n == 'result')]
                    body_lines.append(f'lifted_unimplemented("{name}::{meth}");')
                    ret = 'E_NOTIMPL'
                sig = ', '.join(params)
                lines.append(f'    HRESULT STDMETHODCALLTYPE {meth}({sig}) override {{ ' + ' '.join(body_lines) + f' return {ret}; }}')
            lines.append('};')
    return '\n'.join(lines) + '\n'


def objs(b, odir):
    """the DLL's .cpp files, compiled over its generated stubs"""
    abi = b.winrt_abi_flags({'winrt_abi': True})
    gen = os.path.join(odir, 'microsoft_ui_input_gen')
    os.makedirs(gen, exist_ok=True)
    text = stubs(abi[1])
    path = os.path.join(gen, 'stubs.h')
    if not os.path.exists(path) or open(path).read() != text:   # (unchanged text keeps its time)
        with open(path, 'w') as f:
            f.write(text)
    flags = b.cflags() + abi + ['-I', gen, '-std=c++17', '-fno-exceptions', '-fno-rtti', '-Wno-unused-private-field']
    srcs = [os.path.join(HERE, f) for f in sorted(os.listdir(HERE)) if f.endswith('.cpp')]
    headers = [path] + [os.path.join(HERE, f) for f in os.listdir(HERE) if f.endswith('.h')]
    return b.compile_many(srcs, odir, 'microsoft_ui_input_', flags, headers, compiler='clang++')
