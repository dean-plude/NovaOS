#!/usr/bin/env python3
"""Writes the header the Windows SDK's message compiler (mc.exe -um -p Trace)
makes from Microsoft's XAML ETW manifest
(dxaml/xcp/plat/win/desktop/Microsoft-Windows-XAML-ETW.man), with every
event compiled out: NovaOS has no ETW consumers, so EventEnabledX() is
FALSE and TraceX(...) does nothing (its arguments are not evaluated, as with
a disabled event on Windows).  Usage: etwgen.py MANIFEST OUT.h"""
import re, sys


def main(man, out):
    text = open(man, encoding='utf-8-sig').read()
    lines = ['/* Generated by userland/windows_ui_xaml/etwgen.py from %s: do not edit. */' % man.split('/')[-1],
             '#pragma once', '#include <windows.h>', '#include <evntprov.h>', '']
    for prov in re.finditer(r'<provider\b(.*?)>', text, re.S):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', prov.group(1)))
        name = re.sub(r'\W', '_', attrs['name'])
        g = attrs['guid'].strip('{}').split('-')
        b = g[3] + g[4]
        lines.append('EXTERN_C __declspec(selectany) const GUID %s = {0x%s, 0x%s, 0x%s, {%s}};' % (
            attrs['symbol'], g[0], g[1], g[2], ', '.join('0x' + b[i:i + 2] for i in range(0, 16, 2))))
        lines.append('#define EventRegister%s() ((ULONG)ERROR_SUCCESS)' % name)
        lines.append('#define EventUnregister%s() ((ULONG)ERROR_SUCCESS)' % name)
    seen = set()
    for ev in re.finditer(r'<event\b(.*?)/?>', text, re.S):
        sym = dict(re.findall(r'(\w+)="([^"]*)"', ev.group(1))).get('symbol')
        if sym and sym not in seen:
            seen.add(sym)
            lines.append('#define EventEnabled%s() FALSE' % sym)
            lines.append('#define Trace%s(...) ((ULONG)ERROR_SUCCESS)' % sym)
    lines += ['', '#ifndef MCGEN_LEVEL_KEYWORD_ENABLED_DEF',
              '#define MCGEN_LEVEL_KEYWORD_ENABLED_DEF(Level, Keyword) FALSE', '#endif']
    new = '\n'.join(lines) + '\n'
    try:
        if open(out).read() == new:
            return 0
    except OSError:
        pass
    open(out, 'w').write(new)
    return 0


if __name__ == '__main__':
    sys.exit(main(*sys.argv[1:]))
