#!/usr/bin/env python3
"""Writes the Windows.UI.Xaml classes the system Windows.UI.Xaml.dll serves.

    tools/winrt/wuxclasses.py [OUT.h]      (default kernel/um/um_wuxaml_classes.h)
    tools/winrt/wuxclasses.py --check      (fails if OUT.h is not current)

Windows lists each Windows Runtime class an in-process server makes under
HKLM\\SOFTWARE\\Microsoft\\WindowsRuntime\\ActivatableClassId\\<class>, its
DllPath naming the DLL; RoGetActivationFactory finds Windows.UI.Xaml's
classes there.  NovaOS's Windows.UI.Xaml.dll (userland/windows_ui_xaml_dll)
is its XAML framework, Microsoft's WinUI 3 source, whose classes are the
lifted Microsoft.UI.Xaml ones, served under their Windows names
(userland/windows_ui_xaml/src/windows_activation.cpp).  The classes listed
are those Windows' metadata (third_party/winmd/Windows.winmd) gives an
activation factory (activatable, static or composable) whose lifted class
the framework's own activation table (Factories.g.cpp) has; the kernel's
registry (kernel/um/um_registry.c) writes a key for each at boot.  See
docs/design/windows-ui-xaml.md.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import winmd
from model import RuntimeClass

TOP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WIN = 'Windows.UI.Xaml.'
MUX = 'Microsoft.UI.Xaml.'
FACTORIES = os.path.join(TOP, 'third_party', 'microsoft-ui-xaml', 'dxaml', 'xcp', 'dxaml', 'lib', 'Factories.g.cpp')
OUT = os.path.join(TOP, 'kernel', 'um', 'um_wuxaml_classes.h')


def classes():
    r = winmd.Reader()
    r.load(os.path.join(TOP, 'third_party', 'winmd', 'Windows.winmd'))
    lifted = set(re.findall(r'XSTRING_PTR_STORAGE\(L"Microsoft\.UI\.Xaml\.([\w.]+)"\)', open(FACTORIES).read()))
    out = []
    for n, t in sorted(r.types.items()):
        if not n.startswith(WIN) or not isinstance(t, RuntimeClass) or n[len(WIN):] not in lifted:
            continue
        if any(a.name.endswith(k) for a in t.attrs for k in ('ActivatableAttribute', 'StaticAttribute',
                                                              'ComposableAttribute')):
            out.append(n)
    return out


def text():
    names = classes()
    return ('/* generated by tools/winrt/wuxclasses.py: the Windows.UI.Xaml classes\n'
            ' * Windows.UI.Xaml.dll serves (%d), each an ActivatableClassId key */\n' % len(names) +
            ''.join('"%s",\n' % n for n in names))


def main(argv):
    if '--check' in argv:
        if open(OUT).read() != text():
            print('%s is not current: run tools/winrt/wuxclasses.py' % os.path.relpath(OUT, TOP))
            return 1
        return 0
    out = argv[0] if argv else OUT
    open(out, 'w').write(text())
    print('wuxclasses: %d classes -> %s' % (len(classes()), out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
