/* Where the default tables go in @jpg (the first scan's SOS marker), or
 * -1 when the frame has its own DHT (or no scan) */
static int dht_spot(const BYTE *jpg, UINT32 len)
{
    if (len < 4 || jpg[0] != 0xFF || jpg[1] != 0xD8) return -1;
    UINT32 i = 2;
    while (i + 4 <= len) {
        if (jpg[i] != 0xFF) return -1;
        BYTE m = jpg[i + 1];
        if (m == 0xFF) { i++; continue; }                              /* (fill bytes) */
        if (m == 0xC4) return -1;
        if (m == 0xDA) return (int)i;
        if (m == 0xD8 || (m >= 0xD0 && m <= 0xD7) || m == 0x01) { i += 2; continue; }
        i += 2 + (UINT32)(jpg[i + 2] << 8 | jpg[i + 3]);
    }
    return -1;
}

BOOL mjpeg_decode(const BYTE *jpg, UINT32 len, UINT32 w, UINT32 h, BYTE *rgb)
{
    if (len > 0x7FFFFFFF - sizeof(g_dht)) return FALSE;
    int spot = dht_spot(jpg, len);
    BYTE *whole = NULL;
    if (spot >= 0) {                                                   /* (no tables: the typical ones) */
        whole = malloc(len + sizeof(g_dht));
        if (!whole) return FALSE;
        memcpy(whole, jpg, (size_t)spot);
        memcpy(whole + spot, g_dht, sizeof(g_dht));
        memcpy(whole + spot + sizeof(g_dht), jpg + spot, len - (UINT32)spot);
        jpg = whole;
        len += sizeof(g_dht);
    }
    int x = 0, y = 0, comp = 0;
    stbi_uc *px = stbi_load_from_memory(jpg, (int)len, &x, &y, &comp, 3);
    free(whole);
    if (!px) return FALSE;
    BOOL ok = (UINT32)x == w && (UINT32)y == h;
    if (ok) memcpy(rgb, px, (size_t)w * h * 3);
    stbi_image_free(px);
    return ok;
}
