#!/usr/bin/env python3
"""gen_ci_roots.py — writes kernel/nt/ci_roots.c, the Microsoft product
roots the kernel's driver signature check (kernel/nt/ci.c) trusts

    gen_ci_roots.py

The certificates are the public ones already in userland/crypt32/roots/
(from Microsoft's PKI repository, https://www.microsoft.com/pkiops/docs/
repository.htm), embedded byte for byte.  Windows' kernel-mode signing
policy accepts driver signatures that chain to these.
"""
import hashlib, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOTS = [('010-microsoft-root-2010.cer', 'Microsoft Root Certificate Authority 2010 (WHQL, attestation, Windows)'),
         ('005-microsoft-root-authority.cer', 'Microsoft Root Certificate Authority (2001: older WHQL signatures)')]


def main():
    ders = [open(os.path.join(ROOT, 'userland', 'crypt32', 'roots', f), 'rb').read() for f, _ in ROOTS]
    out = ['/*',
           ' * ci_roots.c — the Microsoft product roots kernel-mode driver signatures',
           ' * chain to (GENERATED by tools/gen_ci_roots.py, do not edit)',
           ' *',
           ' * Public certificates only, byte for byte the ones in userland/crypt32/roots/',
           ' * (from Microsoft\'s PKI repository, https://www.microsoft.com/pkiops/docs/',
           ' * repository.htm).',
           ' */',
           '#include "../include/types.h"',
           '',
           'const UINT8 g_ci_roots_der[] = {']
    for (f, what), d in zip(ROOTS, ders):
        out.append(f'    /* {what}: {f}, SHA-256 {hashlib.sha256(d).hexdigest().upper()} */')
        out += ['    ' + ' '.join(f'0x{b:02X},' for b in d[i:i + 16]) for i in range(0, len(d), 16)]
    out += ['};',
            'const UINT32 g_ci_roots_len[] = { ' + ', '.join(str(len(d)) for d in ders) + ' };',
            f'const int g_ci_nroots = {len(ders)};', '']
    with open(os.path.join(ROOT, 'kernel', 'nt', 'ci_roots.c'), 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
