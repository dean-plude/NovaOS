/*
 * exports.h — what a Windows driver can import from NovaOS
 *
 * The one list the export tables are made from (exports.c includes it with
 * NT_EXPORT / NT_EXPORT_DATA defined to build them; tools that compare a
 * .sys file's imports with it read the same lines).  Each line names the
 * module a driver imports from and the export; the function is nt_<Name>
 * in kernel/nt/, compiled with the Microsoft x64 calling convention
 * (NT_API).  NT_EXPORT is a routine; NT_EXPORT_DATA is a variable a driver
 * imports by address.  A driver importing anything not listed does not
 * load: the boot log names the image and the missing export.
 *
 * Kept in alphabetical order within each group.  NT_EXPORT_DATA lines must
 * be defined by the includer too (exports.c does; it may expand to nothing).
 */
#ifndef NT_EXPORT_DATA
#define NT_EXPORT_DATA(mod, name)
#endif
